import { describe, it, expect, beforeAll } from 'vitest';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(ROOT, 'app', 'src', 'main', 'assets', 'src', 'data', 'plan-bible-words.js');

const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
// Hash before the module is first imported: importing it must not rewrite
// the generated file (the main guard), so this is the comparison baseline.
const hashBeforeImport = sha(OUT_FILE);

let gen;
beforeAll(async () => {
  gen = await import('./gen-bible-words.mjs');
});

const countWords = (ch) => ch.words; // fixture chapters carry their count

function fixtureBooks() {
  return {
    BOOKS: {
      genesis: { chapters: [{ words: 10 }, { words: 20 }] },
      exodus: { chapters: [{ words: 5 }] },
      matthew: { chapters: [{ words: 7 }, { words: 8 }, { words: 9 }] },
    },
    MATTHEW: { chapters: [{ words: 100 }, { words: 101 }, { words: 102 }] },
    TABLE: [['genesis', 'Genesis', 2], ['exodus', 'Exodus', 1], ['matthew-plain', 'Matthew', 3]],
  };
}

describe('buildChapterWords', () => {
  it('counts every chapter in table order', () => {
    const { BOOKS, MATTHEW, TABLE } = fixtureBooks();
    expect(gen.buildChapterWords(BOOKS, MATTHEW, TABLE, countWords)).toEqual({
      genesis: [10, 20],
      exodus: [5],
      'matthew-plain': [7, 8, 9],
    });
  });

  it('falls back to MATTHEW when BOOKS has no matthew', () => {
    const { BOOKS, MATTHEW, TABLE } = fixtureBooks();
    delete BOOKS.matthew;
    const out = gen.buildChapterWords(BOOKS, MATTHEW, TABLE, countWords);
    expect(out['matthew-plain']).toEqual([100, 101, 102]);
  });

  it('throws naming the missing book', () => {
    const { BOOKS, MATTHEW, TABLE } = fixtureBooks();
    delete BOOKS.exodus;
    expect(() => gen.buildChapterWords(BOOKS, MATTHEW, TABLE, countWords)).toThrow('no book exodus');
  });

  it('throws when the chapter count disagrees with the table', () => {
    const { BOOKS, MATTHEW, TABLE } = fixtureBooks();
    BOOKS.genesis.chapters.push({ words: 1 });
    expect(() => gen.buildChapterWords(BOOKS, MATTHEW, TABLE, countWords)).toThrow('genesis has 3 chapters, the table says 2');
  });

  it('throws when a book has no chapters array', () => {
    const { BOOKS, MATTHEW, TABLE } = fixtureBooks();
    BOOKS.exodus = {};
    expect(() => gen.buildChapterWords(BOOKS, MATTHEW, TABLE, countWords)).toThrow('no book exodus');
  });
});

describe('renderPlanBibleWords', () => {
  it('renders the frozen export with a formatted total', () => {
    const out = { genesis: [10, 20], exodus: [5] };
    const { body, total } = gen.renderPlanBibleWords(out);
    expect(total).toBe(35);
    expect(body).toContain('35 words.');
    expect(body).toContain('export const BIBLE_CHAPTER_WORDS = Object.freeze({"genesis":[10,20],"exodus":[5]});');
    expect(body).toContain('GENERATED by tools/gen-bible-words.mjs');
    expect(body.endsWith('\n')).toBe(true);
  });

  it('formats large totals with commas', () => {
    const { body } = gen.renderPlanBibleWords({ a: [1234567] });
    expect(body).toContain('1,234,567 words.');
  });
});

describe('loadBundles', () => {
  function fakeAssets(bibleJs, matthewJs) {
    const dir = mkdtempSync(join(tmpdir(), 'gbw-'));
    const dist = join(dir, 'dist');
    mkdirSync(dist);
    writeFileSync(join(dist, 'bundle-a-bible.js'), bibleJs);
    writeFileSync(join(dist, 'bundle-a-matthew.js'), matthewJs);
    return dir;
  }

  it('loads BOOKS and MATTHEW from fake bundles', () => {
    const dir = fakeAssets(
      'var BOOKS = { genesis: { chapters: [1, 2] } };',
      'var MATTHEW_PLAIN = { chapters: [3] };',
    );
    try {
      const { BOOKS, MATTHEW } = gen.loadBundles(dir);
      expect(BOOKS).toEqual({ genesis: { chapters: [1, 2] } });
      expect(MATTHEW).toEqual({ chapters: [3] });
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('throws when the bible bundle has no BOOKS', () => {
    const dir = fakeAssets('// no BOOKS here', '');
    try {
      expect(() => gen.loadBundles(dir)).toThrow('BOOKS not found in bundle-a-bible.js');
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe('import + regeneration are side-effect-safe', () => {
  it('importing the module does not rewrite the generated file', () => {
    expect(sha(OUT_FILE)).toBe(hashBeforeImport);
  });

  it('running the generator regenerates byte-identical output', { timeout: 60000 }, () => {
    const before = sha(OUT_FILE);
    const out = execFileSync('node', ['tools/gen-bible-words.mjs'], { cwd: ROOT, encoding: 'utf8' });
    expect(out).toMatch(/wrote plan-bible-words.js: 66 books,/);
    expect(sha(OUT_FILE)).toBe(before);
  });
});
