#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════
   tools/build-kjv-alias.mjs — the KJV words no indexed text holds, and the
   verses the KJV holds them in (search plan S1, 2026-10-05)
   ═══════════════════════════════════════════════════════════════════════
   The index holds the reader's edition (NKJV by default), so a word only the
   KJV has ("begat", "mitre", "pretence", "wist") found nothing and the typo
   fallback "corrected" it to a neighbour (beat, mire, presence, wits). This
   writes src/search/kjv-alias.js: each such word with its verses, which the
   engine searches when the index has never heard the word.

   Usage:  node tools/build-kjv-alias.mjs          (write)
           node tools/build-kjv-alias.mjs --check  (exit 1 when the file is stale)
   ═══════════════════════════════════════════════════════════════════════ */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { docs as buildDocs, kjvVerses, ASSETS } from './search-bench/corpus.mjs';

const OUT = path.join(ASSETS, 'src/search/kjv-alias.js');
const { kjvEncode } = await import(pathToFileURL(path.join(ASSETS, 'src/search/tokenize.js')).href);

/** Every word any indexed text holds (the shipped index's NKJV build). */
const known = new Set();
for (const d of await buildDocs()) for (const t of kjvEncode((d.text || '') + ' ' + (d.title || ''))) known.add(t);

const KJV = kjvVerses();
const books = Object.keys(KJV);
/** @type {Map<string, Array<[number, number, number]>>} */
const post = new Map();
books.forEach((b, bi) => {
  for (const c of Object.keys(KJV[b]).map(Number).sort((x, y) => x - y)) {
    for (const v of KJV[b][c]) {
      for (const t of new Set(kjvEncode(v.text))) {
        if (known.has(t) || /\d/.test(t) || t.length < 3) continue;
        if (!post.has(t)) post.set(t, []);
        /** @type {Array<[number, number, number]>} */ (post.get(t)).push([bi, c, v.n]);
      }
    }
  }
});

// One line a word: "word<TAB>B.C.V,C.V,B.C.V..." in base 36, the book given only when it changes.
const lines = [...post.keys()].sort().map((w) => {
  let prev = -1;
  const refs = /** @type {Array<[number, number, number]>} */ (post.get(w)).map(([b, c, v]) => {
    const s = (b !== prev ? b.toString(36) + '.' : '') + c.toString(36) + '.' + v.toString(36);
    prev = b;
    return s;
  });
  return w + '\t' + refs.join(',');
});

const body = `/* GENERATED by tools/build-kjv-alias.mjs from data/bible-kjv.js: do not edit.
   The KJV words no indexed text holds (${post.size}), each with the verses that hold it,
   for a reader of another edition who remembers the KJV ("begat", "mitre"). */
export const KJV_ALIAS_BOOKS = ${JSON.stringify(books)};
export const KJV_ALIAS = ${JSON.stringify(lines.join('\n'))};
`;

if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (now !== body) {
    console.error('[kjv-alias] src/search/kjv-alias.js is stale: run node tools/build-kjv-alias.mjs');
    process.exit(1);
  }
  console.log(`[kjv-alias] current (${post.size} words)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`[kjv-alias] wrote ${OUT}: ${post.size} words, ${body.length} bytes`);
}
