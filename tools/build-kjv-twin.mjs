#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════
   tools/build-kjv-twin.mjs — every verse's KJV wording, for the search to
   read beside the reader's edition (search200 fix1 "ed", 2026-10-19)
   ═══════════════════════════════════════════════════════════════════════
   Writes search-kjv-twin.json at the assets root from data/bible-kjv.js:
   each verse's tokens as kjvEncode reads them, sentence by sentence
   (src/search/kjv-twin.js encodeKjvTwin has the format). The app fetches it
   beside the index (ui/_entry-d.js setKjvTwinSource); the service worker
   keeps it offline and the APK packages it.

   Usage:  node tools/build-kjv-twin.mjs          (write)
           node tools/build-kjv-twin.mjs --check  (exit 1 when the file is stale)
   ═══════════════════════════════════════════════════════════════════════ */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { kjvVerses, ASSETS } from './search-bench/corpus.mjs';

const OUT = path.join(ASSETS, 'search-kjv-twin.json');
const { encodeKjvTwin, parseKjvTwin } = await import(pathToFileURL(path.join(ASSETS, 'src/search/kjv-twin.js')).href);

const twin = encodeKjvTwin(kjvVerses(), 'GENERATED by tools/build-kjv-twin.mjs from src/data/bible-kjv.js: do not edit. ' +
  'Every KJV verse as the search reads it (src/search/kjv-twin.js).');
const body = JSON.stringify(twin) + '\n';
const read = parseKjvTwin(JSON.parse(body));
const verses = read.vFrom.length - 1;

if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (now !== body) {
    console.error('[kjv-twin] search-kjv-twin.json is stale: run node tools/build-kjv-twin.mjs');
    process.exit(1);
  }
  console.log(`[kjv-twin] current (${verses} verses, ${read.words.length} words)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`[kjv-twin] wrote ${OUT}: ${verses} verses, ${read.words.length} words, ${body.length} bytes`);
}
