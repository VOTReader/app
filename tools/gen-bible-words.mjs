// @ts-nocheck
// mw18: writes app/src/main/assets/src/data/plan-bible-words.js, the NKJV words of every Bible chapter,
// so a reading plan can say "about 13 min" before (or without) the 5 MB Bible corpus loading.
// Counts with the app's own countItemWords. Run after the Bible corpus changes:
//   node tools/gen-bible-words.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'app/src/main/assets');
const { countItemWords } = await import(pathToFileURL(path.join(assets, 'src/utils/word-count.js')).href);
const { BIBLE_BOOKS } = await import(pathToFileURL(path.join(assets, 'src/data/reading-plans.js')).href);

const ctx = { window: {}, console };
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ['dist/bundle-a-bible.js', 'dist/bundle-a-matthew.js']) {
  vm.runInContext(fs.readFileSync(path.join(assets, f), 'utf8') + '\n;globalThis.__B = typeof BOOKS !== "undefined" ? BOOKS : globalThis.__B; globalThis.__M = typeof MATTHEW_PLAIN !== "undefined" ? MATTHEW_PLAIN : (typeof MATTHEW !== "undefined" ? MATTHEW : globalThis.__M);', ctx, { filename: f });
}
const BOOKS = ctx.__B || ctx.window.BOOKS;
const MATTHEW = ctx.__M || ctx.window.MATTHEW_PLAIN || ctx.window.MATTHEW;
if (!BOOKS) throw new Error('BOOKS not found in bundle-a-bible.js');

const out = {};
for (const [bid, , n] of BIBLE_BOOKS) {
  const book = bid === 'matthew-plain' ? (BOOKS.matthew || MATTHEW) : BOOKS[bid];
  if (!book || !Array.isArray(book.chapters)) throw new Error('no book ' + bid);
  if (book.chapters.length !== Number(n)) throw new Error(bid + ' has ' + book.chapters.length + ' chapters, the table says ' + n);
  out[bid] = book.chapters.map((ch) => countItemWords(ch));
}
const total = Object.values(out).flat().reduce((a, b) => a + b, 0);
const body = `/* GENERATED by tools/gen-bible-words.mjs from dist/bundle-a-bible.js (NKJV): do not edit.
   The words of every Bible chapter, counted with utils/word-count.js countItemWords, so a reading
   plan can show minutes without loading the Bible corpus (mw18). ${total.toLocaleString('en-US')} words. */

/** @type {Readonly<Record<string, number[]>>} bookId (as in data/reading-plans.js BIBLE_BOOKS) -> words per chapter */
export const BIBLE_CHAPTER_WORDS = Object.freeze(${JSON.stringify(out)});
`;
fs.writeFileSync(path.join(assets, 'src/data/plan-bible-words.js'), body);
console.log('wrote plan-bible-words.js:', Object.keys(out).length, 'books,', total, 'words');
