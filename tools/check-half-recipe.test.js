/* check-half-recipe — REFUSE a tree that changed source and shipped the
   base's generated bytes. The gate takes CLI args and runs git in the
   process cwd, so each case builds a throwaway git repo (base commit +
   head commit) and runs the real tools/check-half-recipe.mjs as a child
   process with cwd set to that repo, exactly as CI does. Fully offline
   (no origin, no fetch); every verdict is pinned by the fixture, not by
   the live tree. */

import { describe, it, expect, afterEach } from 'vitest';
import { spawnSync } from './test-spawn.js'; // file stdio: no pipe another worker's child can hold
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, rmSync } from 'fs';
import { tmpdir } from 'os';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const GATE = resolve(HERE, 'check-half-recipe.mjs');

const repos = [];
afterEach(() => { for (const r of repos.splice(0)) rmSync(r, { recursive: true, force: true }); });

const A = 'app/src/main/assets';
const GIT_ENV = {
  ...process.env,
  GIT_AUTHOR_NAME: 'test',
  GIT_AUTHOR_EMAIL: 'test@example.com',
  GIT_COMMITTER_NAME: 'test',
  GIT_COMMITTER_EMAIL: 'test@example.com',
};

function git(cwd, args) {
  const r = spawnSync('git', args, { encoding: 'utf8', cwd, env: GIT_ENV });
  if (r.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${r.stderr}`);
  return r.stdout;
}

function write(root, rel, text) {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
}

/** Build a throwaway repo with one base commit: distCount files under
 * dist/ (floor 8), srcCount .js files under src/ (floor 100), and the
 * rootJs names quoted by tools/build.py (app.css + these make the root
 * inputs; floor 3). Returns the repo root. */
function makeRepo({ distCount = 10, srcCount = 100, rootJs = ['root-a.js', 'root-b.js'] } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'vot-half-recipe-'));
  repos.push(root);
  git(root, ['init', '-q', '-b', 'main']);
  for (let i = 0; i < distCount; i++) write(root, `${A}/dist/f${i}.js`, `// dist ${i}\n`);
  write(root, `${A}/service-worker.js`, '// sw\n');
  write(root, `${A}/index.html`, '<html></html>\n');
  write(root, `${A}/app.css`, ':root {}\n');
  for (const name of rootJs) write(root, `${A}/${name}`, `// ${name}\n`);
  for (let i = 0; i < srcCount; i++) write(root, `${A}/src/f${String(i).padStart(3, '0')}.js`, `// src ${i}\n`);
  const quoted = rootJs.map((n) => `'${n}'`).join(', ');
  write(root, 'tools/build.py', `# build\nFILES = [${quoted}]\n`);
  git(root, ['add', '-A']);
  git(root, ['commit', '-q', '-m', 'base']);
  return root;
}

/** Commit a mutation on top of the base; `mutate(root)` edits files. */
function headCommit(root, mutate, message = 'head') {
  mutate(root);
  git(root, ['add', '-A']);
  git(root, ['commit', '-q', '-m', message]);
}

/** Copy the real gate into the repo's tools/ and run it there, with the
 * repo as cwd — the gate reads everything through git in its cwd. */
function runGate(root, args) {
  const gateCopy = join(root, 'tools', 'check-half-recipe.mjs');
  copyFileSync(GATE, gateCopy);
  const r = spawnSync(process.execPath, [gateCopy, ...args], { encoding: 'utf8', cwd: root });
  return { status: r.status, stdout: r.stdout || '', stderr: r.stderr || '' };
}

describe('check-half-recipe', () => {
  it('refuses a source change with no rebuild, naming the source file', () => {
    const root = makeRepo();
    headCommit(root, (r) => write(r, `${A}/src/f000.js`, '// src 0 — changed\n'));
    const g = runGate(root, ['HEAD~1']);
    expect(g.status).toBe(1);
    expect(g.stdout).toContain('generated paths derived from the base tree : 12  (moved 0)');
    expect(g.stderr).toContain('REFUSE — HALF RECIPE');
    expect(g.stderr).toContain('app/src/main/assets/src/f000.js');
  });

  it('clears when source changed and a generated file moved', () => {
    const root = makeRepo();
    headCommit(root, (r) => {
      write(r, `${A}/src/f000.js`, '// src 0 — changed\n');
      write(r, `${A}/dist/f0.js`, '// dist 0 — rebuilt\n');
    });
    const g = runGate(root, ['HEAD~1']);
    expect(g.status).toBe(0);
    expect(g.stdout).toContain('CLEAR — source changed AND generated output moved.');
  });

  it('clears a tooling-only delta', () => {
    const root = makeRepo();
    headCommit(root, (r) => write(r, 'tools/build.py', "# build\nFILES = ['root-a.js', 'root-b.js']\n# tweak\n"));
    const g = runGate(root, ['HEAD~1']);
    expect(g.status).toBe(0);
    expect(g.stdout).toContain('CLEAR — no non-test source in the delta');
  });

  it('clears a test-only delta', () => {
    const root = makeRepo();
    headCommit(root, (r) => write(r, `${A}/src/f000.test.js`, '// a test, owes no rebuild\n'));
    const g = runGate(root, ['HEAD~1']);
    expect(g.status).toBe(0);
    expect(g.stdout).toContain('CLEAR — no non-test source in the delta');
  });

  it('exits 2 with no args', () => {
    const root = makeRepo();
    const g = runGate(root, []);
    expect(g.status).toBe(2);
    expect(g.stderr).toContain('usage: node tools/check-half-recipe.mjs <base-ref> [head-ref]');
  });

  it('exits 2 for an unresolvable base ref', () => {
    const root = makeRepo();
    const g = runGate(root, ['nope-no-such-ref']);
    expect(g.status).toBe(2);
    expect(g.stderr).toContain("DEAD INSTRUMENT — cannot resolve 'nope-no-such-ref'");
  });

  it('exits 2 when the base dist/ is below the floor', () => {
    const root = makeRepo({ distCount: 5 });
    const g = runGate(root, ['HEAD']);
    expect(g.status).toBe(2);
    expect(g.stderr).toContain('DEAD INSTRUMENT — the dist/ glob returned 5 paths');
  });

  it('exits 2 when the base src tree is below the floor', () => {
    const root = makeRepo({ srcCount: 50 });
    const g = runGate(root, ['HEAD']);
    expect(g.status).toBe(2);
    expect(g.stderr).toContain('DEAD INSTRUMENT — only 50 source files');
  });

  it('exits 2 when the root inputs are below the floor', () => {
    const root = makeRepo({ rootJs: ['root-a.js'] });
    const g = runGate(root, ['HEAD']);
    expect(g.status).toBe(2);
    expect(g.stderr).toContain('DEAD INSTRUMENT — only 2 root build inputs derived');
  });
});
