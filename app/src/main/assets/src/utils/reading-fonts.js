/** @param {string | null | undefined} id @returns {ReadingFontDef | undefined} */
export function readingFontById(id) {
  return READING_FONTS.find((f) => f.id === id);
}

/* Fonts whose FontFace objects are already in document.fonts this page
   lifetime — ensureReadingFont() is called on every settings change and
   must not re-parse buffers or re-add faces. */
const _loadedFonts = new Set();

function _fontApisAvailable() {
  return typeof FontFace === 'function'
    && typeof caches !== 'undefined'
    && typeof document !== 'undefined'
    && !!document.fonts;
}

/**
 * Make a downloadable font usable: serve every file from the vot-fonts
 * cache, fetching + caching any that are missing, then register FontFace
 * entries. Resolves true when the font is ready (or needs no files);
 * REJECTS on a failed fetch (offline / CDN error) with nothing applied —
 * callers own the user-facing failure message.
 * @param {ReadingFontDef | undefined} def
 */
export async function ensureReadingFont(def) {
  if (!def || !def.files || !def.files.length) return true; // built-in
  if (_loadedFonts.has(def.id)) return true;
  if (!_fontApisAvailable()) return false;
  const cache = await caches.open(READING_FONT_CACHE);
  const faces = [];
  for (const f of def.files) {
    let res = await cache.match(f.url);
    if (!res) {
      res = await fetch(f.url, { mode: 'cors' });
      if (!res.ok) throw new Error('font fetch failed: ' + res.status);
      await cache.put(f.url, res.clone());
    }
    // 40–90 KB per file — well under the 1 MB Permanent-Rule-5 line.
    const buf = await res.arrayBuffer();
    faces.push(new FontFace(def.family, buf, { weight: f.weight, style: f.style, display: 'swap' }));
  }
  // Register only after EVERY file decoded — no half-loaded families.
  for (const face of faces) document.fonts.add(face);
  _loadedFonts.add(def.id);
  return true;
}

/**
 * Is every file of a downloadable font already in the cache?
 * Built-ins report true. Used by the picker for "Downloaded" badges and
 * to decide whether selecting needs the download confirm first.
 * @param {ReadingFontDef | undefined} def
 */
export async function isReadingFontCached(def) {
  if (!def || !def.files || !def.files.length) return true;
  if (_loadedFonts.has(def.id)) return true;
  if (!_fontApisAvailable()) return false;
  try {
    const cache = await caches.open(READING_FONT_CACHE);
    for (const f of def.files) {
      if (!(await cache.match(f.url))) return false;
    }
    return true;
  } catch (_e) {
    return false;
  }
}

/**
 * The --font-body value for a fontStyle id. Unknown ids (e.g. a backup
 * from a newer app version) fall back to the default stack — which is
 * also correct for "classic": the #custom-fonts block is disabled there,
 * so 'EB Garamond' resolves to the system serif exactly as before.
 * @param {string | null | undefined} id
 */
export function readingFontCss(id) {
  const def = readingFontById(id);
  return (def && def.css) || "'EB Garamond', serif";
}
