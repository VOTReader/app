/* ═══════════════════════════════════════════════════════════════════════
   reading-fonts — the Reading Font registry + download-on-demand loader
   ═══════════════════════════════════════════════════════════════════════
   Bundled into dist/bundle-b.js (use-settings applies the persisted font at
   boot; the Settings picker in bundle-d reaches these via window globals).

   THE DESIGN (2026-07-31, owner ask "many font choices without file bloat"):
   - settings.fontStyle now holds any READING_FONTS id. "classic" and
     "modern" keep their historical meanings (system serif / bundled
     EB Garamond) so every persisted or backup-imported value stays valid.
   - Only ~45 KB of name-glyph PREVIEW subsets ship with the app
     (fonts/previews/*.woff2, generated by tools/gen-font-previews.mjs) so
     the picker can render each font's name in that font. The FULL font
     downloads on selection from the fontsource CDN (OFL-licensed), is
     stored in the 'vot-fonts-v1' Cache Storage bucket, and from then on
     loads offline like everything else.
   - Loading uses the FontFace API with ArrayBuffer sources (each file is
     40–90 KB — far under Permanent Rule 5's 1 MB blob-read line), so no
     @font-face CSS or font-src CSP entry is involved; only connect-src
     https://cdn.jsdelivr.net (index.html) gates the fetch.
   - The chosen font lands in the --font-body CSS var on <html>; app.css
     routes every body-text font-family through it. Cinzel chrome stays
     Cinzel for every choice except "classic" (which disables the whole
     #custom-fonts block, the pre-2026-07-31 behavior, all-system look).
   ═══════════════════════════════════════════════════════════════════════ */

