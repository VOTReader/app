// @ts-nocheck — reads the shipped KJV wording file with node's fs.
/* The KJV wording the app ships (search-kjv-twin.json, tools/build-kjv-twin.mjs; search200 fix1 "ed"): every verse of
   the KJV, read back as kjvEncode reads it. Reads the shipped file (CI's "KJV wording is current" step rebuilds it
   from data/bible-kjv.js and fails on any difference). */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseKjvTwin } from './kjv-twin.js';
import { kjvEncode } from './tokenize.js';

const FILE = resolve(dirname(fileURLToPath(import.meta.url)), '../../search-kjv-twin.json');
const J = JSON.parse(readFileSync(FILE, 'utf8'));
const T = parseKjvTwin(J);
const verse = (key) => {
  const v = T.keyOf.get(key);
  return Array.from(T.tok.subarray(T.vFrom[v], T.vFrom[v + 1]), (t) => T.words[t]);
};

describe('the shipped KJV wording (search-kjv-twin.json)', () => {
  it('says it is generated, and holds the whole KJV: 66 books, 1,189 chapters, 31,102 verses', () => {
    expect(J.about).toMatch(/GENERATED by tools\/build-kjv-twin\.mjs/);
    expect(J.books.length).toBe(66);
    expect(J.chapters.reduce((a, c) => a + c.length, 0)).toBe(1189);
    expect(T.vFrom.length - 1).toBe(31102);
  });

  it('reads its verses as kjvEncode reads them, Matthew by the plain chapter’s name', () => {
    expect(verse('genesis:1:1')).toEqual(kjvEncode('In the beginning God created the heaven and the earth.'));
    expect(verse('john:11:35')).toEqual(kjvEncode('Jesus wept.'));
    expect(verse('matthew-plain:1:2')).toContain('begat');
    expect(T.keyOf.has('matthew:1:1')).toBe(false);
  });
});
